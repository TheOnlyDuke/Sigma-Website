/**
 * Validates and retrieves a learning topic by slug (supports both English and Persian slugs).
 * Returns null if topic does not exist.
 */
export const getTopicBySlug = (slug) => {
  if (!slug) return null;
  const decoded = decodeURIComponent(slug).trim().toLowerCase();

  // Direct key lookup
  if (learningTopics[decoded]) {
    return learningTopics[decoded];
  }

  // Lookup in aliases or slug property
  for (const key of Object.keys(learningTopics)) {
    const topic = learningTopics[key];
    if (
      topic.slug?.toLowerCase() === decoded ||
      topic.id?.toLowerCase() === decoded ||
      topic.title === decoded ||
      topic.aliases?.some((a) => a.toLowerCase() === decoded)
    ) {
      return topic;
    }
  }

  return null;
};

